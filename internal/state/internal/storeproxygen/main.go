// Command storeproxygen generates the exhaustive operation-pinning Store facade.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "store.go", nil, 0)
	if err != nil {
		return err
	}
	interfaces := make(map[string]*ast.InterfaceType)
	ast.Inspect(file, func(node ast.Node) bool {
		if declaration, ok := node.(*ast.TypeSpec); ok {
			if definition, ok := declaration.Type.(*ast.InterfaceType); ok {
				interfaces[declaration.Name.Name] = definition
			}
		}
		return true
	})
	methods := make(map[string]*ast.FuncType)
	seen := make(map[string]bool)
	var collect func(string) error
	collect = func(name string) error {
		definition := interfaces[name]
		if definition == nil || seen[name] {
			return fmt.Errorf("unknown or repeated embedded interface %s", name)
		}
		seen[name] = true
		for _, field := range definition.Methods.List {
			if len(field.Names) == 0 {
				embedded, ok := field.Type.(*ast.Ident)
				if !ok {
					return fmt.Errorf("unsupported embedded interface in %s", name)
				}
				if err := collect(embedded.Name); err != nil {
					return err
				}
				continue
			}
			method, ok := field.Type.(*ast.FuncType)
			if !ok || len(field.Names) != 1 || methods[field.Names[0].Name] != nil {
				return fmt.Errorf("unsupported or duplicate Store method in %s", name)
			}
			methods[field.Names[0].Name] = method
		}
		return nil
	}
	if err := collect("Store"); err != nil {
		return err
	}
	imports := make(map[string]string)
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return err
		}
		name := path[strings.LastIndex(path, "/")+1:]
		if spec.Name != nil {
			name = spec.Name.Name
		}
		imports[name] = path
	}
	usedImports := make(map[string]string)
	var names []string
	for name, method := range methods {
		names = append(names, name)
		if method.Results == nil || len(method.Results.List) == 0 {
			usedImports["slog"] = "log/slog"
		}
		ast.Inspect(method, func(node ast.Node) bool {
			if selector, ok := node.(*ast.SelectorExpr); ok {
				if qualifier, ok := selector.X.(*ast.Ident); ok && imports[qualifier.Name] != "" {
					usedImports[qualifier.Name] = imports[qualifier.Name]
				}
			}
			return true
		})
	}
	sort.Strings(names)
	var generated bytes.Buffer
	generated.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage state\n\n")
	if len(usedImports) > 0 {
		generated.WriteString("import (\n")
		var qualifiers []string
		for qualifier := range usedImports {
			qualifiers = append(qualifiers, qualifier)
		}
		sort.Strings(qualifiers)
		for _, qualifier := range qualifiers {
			path := usedImports[qualifier]
			if qualifier == path[strings.LastIndex(path, "/")+1:] {
				fmt.Fprintf(&generated, "%q\n", path)
			} else {
				fmt.Fprintf(&generated, "%s %q\n", qualifier, path)
			}
		}
		generated.WriteString(")\n\n")
	}
	for _, name := range names {
		method := methods[name]
		var signature bytes.Buffer
		if err := printer.Fprint(&signature, fset, method); err != nil {
			return err
		}
		var args []string
		for _, parameter := range method.Params.List {
			if len(parameter.Names) == 0 {
				return fmt.Errorf("store method %s requires named parameters", name)
			}
			for _, parameterName := range parameter.Names {
				arg := parameterName.Name
				if arg == "store" || arg == "release" || arg == "s" || arg == "err" {
					return fmt.Errorf("store method %s uses a facade-reserved parameter name", name)
				}
				if _, variadic := parameter.Type.(*ast.Ellipsis); variadic {
					arg += "..."
				}
				args = append(args, arg)
			}
		}
		fmt.Fprintf(&generated, "func (s *onlineMigrationStore) %s%s {\nstore, release, err := s.pin()\nif err != nil {\n", name, strings.TrimPrefix(signature.String(), "func"))
		if method.Results == nil || len(method.Results.List) == 0 {
			fmt.Fprintf(&generated, "slog.Warn(\"state operation rejected\", \"method\", %q, \"error\", err)\nreturn\n", name)
		} else {
			results := method.Results.List
			last, ok := results[len(results)-1].Type.(*ast.Ident)
			if !ok || last.Name != "error" {
				return fmt.Errorf("store method %s requires a final error result", name)
			}
			var zeros []string
			for i, result := range results[:len(results)-1] {
				if len(result.Names) > 1 {
					return fmt.Errorf("store method %s has grouped result names", name)
				}
				var typ bytes.Buffer
				if err := printer.Fprint(&typ, fset, result.Type); err != nil {
					return err
				}
				zero := fmt.Sprintf("zero%d", i)
				fmt.Fprintf(&generated, "var %s %s\n", zero, typ.String())
				zeros = append(zeros, zero)
			}
			zeros = append(zeros, "err")
			fmt.Fprintf(&generated, "return %s\n", strings.Join(zeros, ", "))
		}
		generated.WriteString("}\ndefer release()\n")
		if method.Results != nil && len(method.Results.List) > 0 {
			generated.WriteString("return ")
		}
		fmt.Fprintf(&generated, "store.%s(%s)\n}\n\n", name, strings.Join(args, ", "))
	}
	formatted, err := format.Source(generated.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("online_migration_store_generated.go", formatted, 0o644)
}
